// Standard 18-column layout: rows 1-8 are the main table (with a spacer row 8),
// rows 9-10 hold the f-block. Lanthanides and actinides reserve a tile in the
// main table and the rest of the series lives in the f-block below.
export function getLayoutPosition(z) {
  if (z >= 58 && z <= 71) return { x: z - 55, y: 9 } // 58 -> 3 ... 71 -> 16
  if (z >= 90 && z <= 103) return { x: z - 87, y: 10 } // 90 -> 3 ... 103 -> 16
  if (z === 1) return { x: 1, y: 1 }
  if (z === 2) return { x: 18, y: 1 }
  if (z <= 4) return { x: z - 2, y: 2 } // 3,4 -> 1,2
  if (z <= 10) return { x: z + 8, y: 2 } // 5-10 -> 13-18
  if (z <= 12) return { x: z - 10, y: 3 } // 11,12 -> 1,2
  if (z <= 18) return { x: z, y: 3 } // 13-18 -> 13-18
  if (z <= 36) return { x: z - 18, y: 4 } // period 4: 19 -> 1 ... 36 -> 18
  if (z <= 54) return { x: z - 36, y: 5 } // period 5: 37 -> 1 ... 54 -> 18
  if (z <= 56) return { x: z - 54, y: 6 } // 55,56 -> 1,2
  if (z === 57) return { x: 3, y: 6 } // La in main table
  if (z <= 86) return { x: z - 68, y: 6 } // 72 -> 4 ... 86 -> 18
  if (z <= 88) return { x: z - 86, y: 7 } // 87,88 -> 1,2
  if (z === 89) return { x: 3, y: 7 } // Ac in main table
  return { x: z - 100, y: 7 } // 104 -> 4 ... 118 -> 18
}

export const GROUP_FOR = (z) => {
  const p = getLayoutPosition(z)
  return p.y <= 7 ? p.x : null
}

