export type ElementCategory =
  | 'alkali-metal'
  | 'alkaline-earth-metal'
  | 'transition-metal'
  | 'post-transition-metal'
  | 'metalloid'
  | 'nonmetal'
  | 'halogen'
  | 'noble-gas'
  | 'lanthanide'
  | 'actinide'
  | 'unknown';

export type ElementState = 'solid' | 'liquid' | 'gas' | 'unknown';

export interface Element {
  symbol: string;
  name: string;
  atomicNumber: number;
  atomicMass: number;
  category: ElementCategory;
  /** Display row in periodic table (1-9; 8=lanthanides, 9=actinides) */
  period: number;
  /** Display column 1-18 */
  group: number;
  state: ElementState;
  electronConfiguration: string;
  electronegativity?: number;
  meltingPoint?: number; // °C
  boilingPoint?: number; // °C
  density?: number;      // g/cm³ (or g/L for gases)
  description: string;
  funFacts: string[];
  uses: string[];
  occurrence: string;
}

